export type TKey = keyof typeof dict.fa;

export function makeT(lang: Lang) {
  return (k: TKey, vars?: Record<string, string>): string => {
    let s: string = dict[lang][k] ?? dict.fa[k] ?? k;
    if (vars) for (const [key, v] of Object.entries(vars)) s = s.replace(`{${key}}`, v);
    return s;
  };
}

export const faDigits = (s: string) =>
  s.replace(/\d/g, (d) => "۰۱۲۳۴۵۶۷۸۹"[Number(d)]);
